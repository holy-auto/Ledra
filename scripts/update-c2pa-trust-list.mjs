// Fetch the official C2PA Trust List and TSA Trust List and write them into the product as a module.
//   node scripts/update-c2pa-trust-list.mjs
// c2pa-node 0.9.7 does not fetch trust-anchor URLs, so the PEM text has to ship with the build.
// The lists change over time: re-run this, review the diff (certificates added/removed), and commit.
import { createHash, X509Certificate } from "node:crypto";
import { writeFileSync } from "node:fs";

const BASE = "https://raw.githubusercontent.com/c2pa-org/conformance-public/main/trust-list";
const LISTS = { C2PA_TRUST_LIST_PEM: "C2PA-TRUST-LIST.pem", C2PA_TSA_TRUST_LIST_PEM: "C2PA-TSA-TRUST-LIST.pem" };
const OUT = new URL("../src/lib/anchoring/c2paTrustList.generated.ts", import.meta.url);

const blocks = (pem) => pem.match(/-----BEGIN CERTIFICATE-----[\s\S]+?-----END CERTIFICATE-----/g) ?? [];

let out = `// Generated by scripts/update-c2pa-trust-list.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit.\n`;
out += `// Source: ${BASE}/\n`;
for (const [name, file] of Object.entries(LISTS)) {
  const res = await fetch(`${BASE}/${file}`);
  if (!res.ok) throw new Error(`${file}: HTTP ${res.status}`);
  const pem = await res.text();
  const certs = blocks(pem);
  if (certs.length === 0) throw new Error(`${file}: no certificates`);
  for (const c of certs) new X509Certificate(c); // throws on a malformed entry
  const sha = createHash("sha256").update(pem).digest("hex");
  out += `\n// ${file}: ${certs.length} certificates, sha256 ${sha}\n`;
  out += `export const ${name} = \`${certs.join("\n")}\n\`;\n`;
  console.log(`${file}: ${certs.length} certificates`);
}
writeFileSync(OUT, out);
