/**
 * 管理画面ナビゲーションのデータと純粋な導出関数（サーバー/クライアント両用）。
 *
 * Sidebar 本体（"use client"）から分離することで、サーバー側（例: AIナビの
 * navIntent）からも adminCommandItems() 等を安全に呼べるようにする。ここには
 * hooks やブラウザ専用 API を置かない（"use client" を付けない = 環境非依存）。
 */
import type { ReactNode } from "react";
import { type Permission } from "@/lib/auth/permissions";

export type NavItem = {
  href: string;
  label: string;
  exact?: boolean;
  icon: ReactNode;
  requiredPermission?: Permission;
  /** Hide from sidebar — used to suppress unreleased features before launch */
  hidden?: boolean;
  /** Badge key used to look up dynamic badge counts */
  badgeKey?: string;
  /**
   * Platform-admin-only item. Strictly hidden unless the caller is a platform
   * admin (super_admin, or owner/admin of PLATFORM_TENANT_ID). Unlike
   * requiredPermission, this is NOT optimistic — items remain hidden while
   * the role loads so contractors never see a flash of the link.
   */
  platformOnly?: boolean;
  /**
   * 本社専用ユーザ (テナント未所属の組織オーナー / 本社チーム) に表示する項目。
   * これらのユーザは tenant role が無いため通常の requiredPermission では
   * 何も見えない。本社向け画面 (横断ビュー・組織管理) のみ true にする。
   */
  orgUserVisible?: boolean;
  /**
   * L字シェルのゴールドアクセント項目 (証明書など上位機能)。アクティブ時の
   * アイコン/ドットをブルーではなくゴールドで表現し、格を一段上げて見せる。
   */
  gold?: boolean;
  /**
   * 設定・マスタ系項目。サイドバーには出さず、歯車から開く設定ハブ
   * (/admin/settings) にのみ集約する。ラベル逆引き (ADMIN_NAV_LABELS) と
   * パンくずは維持したいので、項目自体は NAV_GROUPS に残したまま描画だけ抑止する。
   */
  hub?: boolean;
  /**
   * AI 自動化の「人の承認待ち」を表す要確認項目 (承認インボックス)。承認待ちが
   * ある時 (badge > 0) はアラート赤ではなく琥珀 (要対応) のバッジ＋アイコン色＋
   * 左の琥珀ラインで強調する。0 件の時は通常項目と同じ見た目。
   */
  attention?: boolean;
  /**
   * 設定ハブでの表示見出し。hub 項目をカテゴリ分けするために使う。
   */
  hubSection?: string;
  /** オンボーディングツアーで指し示すための data-tour 属性値。 */
  dataTour?: string;
};

export type NavGroup = {
  label: string;
  items: NavItem[];
  defaultOpen?: boolean;
};

