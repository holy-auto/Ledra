-- ============================================================
-- 代理店ポータルの通知設定の保存先
--
-- 設定画面には「メール通知を受け取る」のトグルがあり、既定 true で**毎回送信される**が、
-- agents に保存先の列が無かった。zod がそのキーを落としていた間は気付かなかったが、
-- 「保存先の無い項目は保存できないと返す」ようにした結果、
-- **トグルが on（既定）だと設定画面の保存が常に 400 になる**という不具合になった。
-- 代理店単位の設定として持つ。
--
-- 適用済み: 本番へは MCP 経由で version 20260823161810 として適用済み。
-- ファイル名をその version に合わせてあるので CI の db-migrate は適用済みとして飛ばす。
-- ============================================================

alter table public.agents add column if not exists email_notifications boolean not null default true;

comment on column public.agents.email_notifications is
  '代理店ポータルの通知設定。設定画面のトグルの保存先';
